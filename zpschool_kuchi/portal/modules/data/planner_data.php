function planner_canonical_subject(string $subject): string
{
    $s = trim($subject);
    return planner_subject_aliases()[$s] ?? $s;
}

/**
 * वार्षिक नियोजन (महिना x विषय x ४ आठवडे) — मूळ डेटा + २०२६ 'खेळू, करू, शिकू'
 * पुस्तकांतील कला/कार्यशिक्षण-व्यावसायिक/शारीरिक शिक्षण घटक (इ. ३, ४, ६).
 */
function planner_annual_weeks(): array
{
    $out = [];
    foreach (planner_annual_weeks_base() as $std => $months) {
        foreach ($months as $m => $subs) {
            foreach ($subs as $sub => $weeks) {
                $out[$std][$m][planner_canonical_subject((string) $sub)] = $weeks;
            }
        }
    }
    foreach (planner_annual_weeks_2026() as $std => $months) {
        foreach ($months as $m => $subs) {
            foreach ($subs as $sub => $weeks) {
                $out[$std][$m][$sub] = $weeks;
            }
        }
    }
    return $out;
}
