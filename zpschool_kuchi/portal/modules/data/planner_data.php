/** एका दिवसातील शिकवण्याच्या तासिकांची संख्या (शनिवार सकाळ सत्र = ६) */
function planner_period_count(int $day = 1): int
{
    return $day === 6 ? 6 : 9;
}

/** मधल्या सुट्ट्या — [कोणत्या तासिकेनंतर => मजकूर] (वेळापत्रकात दाखवण्यासाठी) */
function planner_breaks(int $day = 1): array
