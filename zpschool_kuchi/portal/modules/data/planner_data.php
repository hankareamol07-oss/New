    return [4 => 'मोठी सुट्टी १.१५ ते १.५५', 7 => 'लहान सुट्टी ३.४० ते ३.५०'];
}

function planner_days(): array
{
    return [1 => 'सोमवार', 2 => 'मंगळवार', 3 => 'बुधवार', 4 => 'गुरुवार', 5 => 'शुक्रवार', 6 => 'शनिवार'];
