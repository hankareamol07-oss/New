/**
 * वेळापत्रक साचा (मानक शैली) — तासिका १ ते ९ (सोम-शुक्र) व १ ते ६ (शनिवार).
 * परिपाठ ही "*" तासिका वेगळी असल्याने येथे क्रमांकित तासिकांतच विषय भरले जातात.
 * मुख्य विषयांना अधिक व समृद्धीकरण विषयांना कमी वारंवारता (भारित यादी).
 */
function planner_timetable_for_std(int $std): array
{
    $core = planner_subjects_for_std($std);
    $extra = planner_extra_subjects($std);
    $nc = count($core);
    $ne = count($extra);
    $grid = [];
    $e = 0;
    foreach (planner_days() as $day => $_n) {
        $count = planner_period_count($day);
        // सुरुवातीच्या तासिका मुख्य विषय (दिवसागणिक क्रम फिरतो — मराठी/गणित/इंग्रजी दररोज सकाळी),
        // शेवटच्या २ तासिका (शनिवार शेवटची १) समृद्धीकरण / AEP.
        $coreSlots = $day === 6 ? $count - 1 : $count - 2;
        for ($p = 1; $p <= $count; $p++) {
            if ($p <= $coreSlots) {
                $grid[$day][$p] = $core[($p - 1 + ($day - 1)) % $nc];
            } else {
                $grid[$day][$p] = $extra[($e++) % $ne];
            }
        }
    }
    return $grid;
}

/** प्रदर्शनासाठी विषयनाव — सेमी माध्यमात गणित->Maths, विज्ञान->Gen Science */
function tachan_display_subject(string $subject, string $medium = 'marathi'): string
{
    $semi = mb_strpos($medium, 'सेमी') !== false || stripos($medium, 'semi') !== false;
    if (!$semi) return $subject;
    if (mb_strpos($subject, 'गणित') !== false) return 'Maths';
    if (mb_strpos($subject, 'विज्ञान') !== false) return 'Gen Science';
    return $subject;
}

