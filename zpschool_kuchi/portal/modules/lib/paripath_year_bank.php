            'सोमवार' => '०७:३० AM - ०९:०० AM',
            'मंगळवार' => '०३:०० PM - ०४:३० PM',
            'बुधवार' => '१२:०० PM - ०१:३० PM',
            'गुरुवार' => '०१:३० PM - ०३:०० PM',
            'शुक्रवार' => '१०:३० AM - १२:०० PM',
            'शनिवार' => '०९:०० AM - १०:३० AM'
        ];
        $rahuKaal = $rahuKaalTimes[$var] ?? '०७:३० AM - ०९:०० AM';

        return [
            'date' => $date,
            'location' => 'महाराष्ट्र (पुणे / मुंबई)',
            'hindu_month' => $tithiData['hindu_month'],
