            'tithi' => $tithiData['tithi'],
            'nakshatra' => $nakshatra,
            'yoga' => $yoga,
            'karana' => $karana,
            'var' => $var,
            'ritu' => $ritu,
            'sunrise' => $sunrise,
            'sunset' => $sunset,
            'moonrise' => '०७:४५ PM',
            'moonset' => '०६:२० AM',
            'rahu_kaal' => $rahuKaal,
            'festivals' => $festival ? $festival['name'] : '',
            'festivals_list' => $festival ? [$festival['name']] : [],
            'vrat' => $festival ? ($festival['vrat'] ?? '') : '',
            'is_festival' => $festival ? 1 : 0
        ];
    }

    /**
     * Calculate Amanta Hindu Tithi based on lunar cycle anchors for 2026/2027
     */
    private static function calculateTithi(int $ts): array
    {
        // New Moon (Amavasya) anchors for 2026
        // Format: timestamp => [Hindu month starting next day (Shukla Paksha Pratipada)]
        $newMoons2026 = [
            '2026-01-18' => 'माघ',
            '2026-02-17' => 'फाल्गुन',
            '2026-03-19' => 'चैत्र', // गुढीपाडवा (नवीन वर्ष)
            '2026-04-17' => 'वैशाख',
            '2026-05-16' => 'ज्येष्ठ',
            '2026-06-15' => 'आषाढ',
            '2026-07-14' => 'श्रावण',
            '2026-08-12' => 'भाद्रपद',
            '2026-09-11' => 'अश्विन',
            '2026-10-10' => 'कार्तिक',
            '2026-11-09' => 'मार्गशीर्ष',
            '2026-12-09' => 'पौष',
            '2027-01-08' => 'माघ',
            '2027-02-06' => 'फाल्गुन',
            '2027-03-08' => 'चैत्र'
        ];

        $tithiNames = [
            1 => 'प्रतिपदा', 2 => 'द्वितीया', 3 => 'तृतीया', 4 => 'चतुर्थी',
            5 => 'पंचमी', 6 => 'षष्ठी', 7 => 'सप्तमी', 8 => 'अष्टमी',
            9 => 'नवमी', 10 => 'दशमी', 11 => 'एकादशी', 12 => 'द्वादशी',
            13 => 'त्रयोदशी', 14 => 'चतुर्दशी'
        ];

        // Find closest prior new moon
        $priorNm = '2025-12-20';
        $currentMonth = 'पौष';

        foreach ($newMoons2026 as $nmDate => $nextMonth) {
            $nmTs = strtotime($nmDate);
            if ($ts >= $nmTs) {
                $priorNm = $nmDate;
                $currentMonth = $nextMonth;
            } else {
                break;
            }
        }

        $daysSinceNm = (int)round(($ts - strtotime($priorNm)) / 86400);

        if ($daysSinceNm <= 0) {
            return [
                'hindu_month' => $currentMonth,
                'paksha' => 'कृष्ण पक्ष',
                'tithi' => 'अमावस्या'
            ];
        } elseif ($daysSinceNm < 15) {
            $tNum = min(14, max(1, $daysSinceNm));
            return [
                'hindu_month' => $currentMonth,
                'paksha' => 'शुक्ल पक्ष',
                'tithi' => 'शुक्ल ' . ($tithiNames[$tNum] ?? 'प्रतिपदा')
            ];
        } elseif ($daysSinceNm === 15) {
            return [
                'hindu_month' => $currentMonth,
                'paksha' => 'शुक्ल पक्ष',
                'tithi' => 'पौर्णिमा'
            ];
        } elseif ($daysSinceNm < 30) {
            $tNum = min(14, max(1, $daysSinceNm - 15));
            return [
                'hindu_month' => $currentMonth,
                'paksha' => 'कृष्ण पक्ष',
                'tithi' => 'कृष्ण ' . ($tithiNames[$tNum] ?? 'प्रतिपदा')
            ];
        } else {
            return [
                'hindu_month' => $currentMonth,
                'paksha' => 'कृष्ण पक्ष',
                'tithi' => 'अमावस्या'
            ];
        }
    }

