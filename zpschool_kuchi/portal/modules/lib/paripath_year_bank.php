            'अश्विन', 'कार्तिक' => 'शरद ऋतू',
            'मार्गशीर्ष', 'पौष' => 'हेमंत ऋतू',
            default => 'शिशिर ऋतू'
        };

        // Solar timings (calculated for Maharashtra / Pune / Mumbai coordinates)
        $sunriseHour = 6;
        $sunriseMin = 15 + (int)(15 * sin(($dayOfYear / 365) * 2 * M_PI));
        $sunriseMin = max(0, min(59, $sunriseMin));
        $sunrise = sprintf('%02d:%02d AM', $sunriseHour, $sunriseMin);

        $sunsetHour = 6;
        $sunsetMin = 20 + (int)(30 * cos(($dayOfYear / 365) * 2 * M_PI));
        $sunsetMin = max(0, min(59, $sunsetMin));
