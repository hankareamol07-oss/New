/** क्षमता कोड -> अधिकृत मराठी मजकूर (सर्व क्षेत्रे एकत्र). */
function hpc_fs_competency_text($code = null)
{
    static $map = null;
    if ($map === null) {
        $map = [];
        foreach (hpc_fs_domains() as $dom) {
            foreach ($dom['competencies'] as $c => $t) $map[$c] = $t;
        }
    }
    if ($code === null) return $map;
    return $map[$code] ?? '';
}

/** ध्येय कोड -> अधिकृत मराठी मजकूर. */
function hpc_fs_goal_text($code = null)
{
    static $map = null;
    if ($map === null) {
        $map = [];
        foreach (hpc_fs_domains() as $dom) {
            foreach ($dom['goals'] as $g => $t) $map[$g] = $t;
        }
    }
    if ($code === null) return $map;
    $code = rtrim($code, '*');
    return $map[$code] ?? '';
}

